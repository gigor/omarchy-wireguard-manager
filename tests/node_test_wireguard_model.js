const assert = require('node:assert/strict')
const fs = require('node:fs')
const vm = require('node:vm')
const source = fs.readFileSync('WireGuardModel.js', 'utf8').replace(/^\.pragma library\s*/, '')
const context = {}
vm.runInNewContext(source, context)

assert.equal(context.isValidName('office'), true)
assert.equal(context.isValidName('home-lab'), true)
assert.equal(context.isValidName('a_b+1=2.3'), true)
assert.equal(context.isValidName('a name'), false)
assert.equal(context.isValidName('a/b'), false)
assert.equal(context.isValidName('$(id)'), false)
assert.equal(context.isValidName('1234567890123456'), false)
const same = (actual, expected) => assert.equal(JSON.stringify(actual), JSON.stringify(expected))
same(context.parseFindOutput('office.conf\nhome-lab.conf\nfoo/bar.conf\nlink.conf\n'), ['home-lab', 'link', 'office'])
same(context.parseInterfaces('office home-lab\n'), { office: true, 'home-lab': true })
same(context.parseInterfaces(''), {})
same(context.parseInterfaces('bad/name office;rm'), {})
same(context.discoveryCommand(), ['/usr/bin/find', '/etc/wireguard', '-maxdepth', '1', '-type', 'f', '-name', '*.conf', '-printf', '%f\\n'])
same(context.statusCommand(), ['/usr/bin/wg', 'show', 'interfaces'])
same(context.toggleCommand('office', 'up'), ['/usr/bin/pkexec', '/usr/bin/wg-quick', 'up', '/etc/wireguard/office.conf'])
same(context.toggleCommand('office', 'down'), ['/usr/bin/pkexec', '/usr/bin/wg-quick', 'down', '/etc/wireguard/office.conf'])
same(context.toggleCommand('bad/name', 'up'), [])
same(context.toggleCommand('office', 'sh'), [])
assert.equal(context.configPath('office', '/tmp/not-wireguard'), '/etc/wireguard/office.conf')
assert.equal(context.discoveryCommand('/tmp/not-wireguard')[1], '/etc/wireguard')

